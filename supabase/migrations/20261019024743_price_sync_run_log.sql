create table if not exists public.price_sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null check (status in ('success', 'partial', 'failed')),
  sources_checked integer not null default 0,
  rows_written integer not null default 0,
  details jsonb not null default '{}'::jsonb
);
alter table public.price_sync_runs enable row level security;
revoke all on public.price_sync_runs from anon, authenticated;
grant select, insert on public.price_sync_runs to service_role;